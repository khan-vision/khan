const (
	uuidRe = "/^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/"
	dateRe = "/^\\d{4}-\\d{2}-\\d{2}$/"
	timeRe = "/^\\d{2}:\\d{2}(:\\d{2})?$/"
)

func appendZodFields(out *[]string, fields []crud.FieldMeta) error {
	for _, f := range fields {
		expr, err := zodExpr(f)
		if err != nil {
			return fmt.Errorf("%s: %w", f.Name, err)
		}
		*out = append(*out, propKey(f.Name)+": "+expr)
	}
	return nil
}

func label(f crud.FieldMeta) string {
	if f.Label != "" {
		return f.Label
	}
	return f.Name
}

func zodExpr(f crud.FieldMeta) (string, error) {
	lbl := label(f)
	var e string
	switch f.Kind {
	case validate.String, validate.Text, validate.Phone, validate.Password:
		e = "z.string()"
		min := f.MinLen
		if min == 0 && f.Required && f.Kind != validate.Phone {
			min = 1
		}
		if min > 0 {
			e += fmt.Sprintf(".min(%d, %s)", min, jsStr(minLenMsg(lbl, min, f.Required)))
		}
		if f.MaxLen > 0 {
			e += fmt.Sprintf(".max(%d, %s)", f.MaxLen, jsStr(lbl+": хамгийн ихдээ "+fmt.Sprint(f.MaxLen)+" тэмдэгт"))
		}
	case validate.Email:
		e = "z.email(" + jsStr(lbl+": имэйл хаяг буруу") + ")"
		if f.MaxLen > 0 {
			e += fmt.Sprintf(".max(%d, %s)", f.MaxLen, jsStr(lbl+": хамгийн ихдээ "+fmt.Sprint(f.MaxLen)+" тэмдэгт"))
		}
	case validate.Int:
		e = "z.number().int(" + jsStr(lbl+": бүхэл тоо оруулна уу") + ")"
		if f.Min != nil {
			e += fmt.Sprintf(".min(%s, %s)", fmtNum(*f.Min), jsStr(lbl+": "+fmtNum(*f.Min)+"-аас багагүй байна"))
		}
		if f.Max != nil {
			e += fmt.Sprintf(".max(%s, %s)", fmtNum(*f.Max), jsStr(lbl+": "+fmtNum(*f.Max)+"-аас ихгүй байна"))
		}
	case validate.Money, validate.Number:
		e = "khanDecimal(" + jsStr(lbl) + ", " + fmt.Sprint(decimalScale(f)) + minMaxArgs(f) + ")"
	case validate.Bool:
		e = "z.boolean()"
	case validate.Date:
		e = "z.string().regex(" + dateRe + ", " + jsStr(lbl+": YYYY-MM-DD огноо оруулна уу") + ")"
	case validate.DateTime:
		e = "z.iso.datetime({ offset: true, error: " + jsStr(lbl+": RFC3339 огноо цаг оруулна уу") + " })"
	case validate.Time:
		e = "z.string().regex(" + timeRe + ", " + jsStr(lbl+": HH:MM цаг оруулна уу") + ")"
	case validate.UUID:
		e = "z.string().regex(" + uuidRe + ", " + jsStr(lbl+": id буруу") + ")"
	case validate.Enum:
		if len(f.Enum) > 0 {
			parts := make([]string, len(f.Enum))
			for i, v := range f.Enum {
				parts[i] = jsStr(v)
			}
			e = "z.enum([" + strings.Join(parts, ", ") + "], { error: " + jsStr(lbl+": зөвшөөрөгдөөгүй утга") + " })"
		} else {
			e = "z.string()"
		}
	case validate.JSON:
		// z.unknown() нь түлхүүрийг optional болгодог (дутуу түлхүүр шалгагдахгүй): Required үед z.custom.
		e = "z.unknown()"
		if f.Required && f.Default == nil {
			e = "z.custom<unknown>((v) => v !== undefined, " + jsStr(lbl+" заавал") + ")"
		}
	default:
		return "", fmt.Errorf("үл мэдэгдэх kind %q", f.Kind)
	}
	if f.Pattern != "" && f.Kind != validate.Enum {
		re, err := jsRegExp(f.Pattern)
		if err != nil {
			return "", err
		}
		msg := f.PatternMsg
		if msg == "" {
			msg = lbl + ": формат буруу"
		}
		switch f.Kind {
		case validate.String, validate.Text, validate.Phone, validate.Password, validate.Email:
			e += ".regex(" + re + ", " + jsStr(msg) + ")"
		}
	}
	if f.Nullable {
		e += ".nullable()"
	}
	if optionalOnCreate(f) && f.Kind != validate.JSON {
		e += ".optional()"
	}
	return e, nil
}

func minLenMsg(lbl string, n int, required bool) string {
	if n == 1 && required {
		return lbl + " заавал"
	}
	return lbl + ": хамгийн багадаа " + fmt.Sprint(n) + " тэмдэгт"
}

func decimalScale(f crud.FieldMeta) int {
	if f.Kind == validate.Money {
		return 2
	}
	if f.Scale > 0 {
		return f.Scale
	}
	return 6
}

func minMaxArgs(f crud.FieldMeta) string {
	switch {
	case f.Min != nil && f.Max != nil:
		return ", " + fmtNum(*f.Min) + ", " + fmtNum(*f.Max)
	case f.Min != nil:
		return ", " + fmtNum(*f.Min)
	case f.Max != nil:
		return ", undefined, " + fmtNum(*f.Max)
	}
	return ""
}

// jsRegExp — Go (RE2) pattern → JS `new RegExp(...)`. Урд талын `(?i)` flag, `(?P<n>` нэрлэсэн бүлгийг хөрвүүлнэ;
// JS-д байхгүй `\A \z \Q \C [[:class:]]`-ийг алдаа болгоно.
func jsRegExp(p string) (string, error) {
	flags := ""
	for strings.HasPrefix(p, "(?") {
		end := strings.Index(p, ")")
		if end < 0 {
			break
		}
		fl := p[2:end]
		if fl == "" || strings.Trim(fl, "ims") != "" {
			break
		}
		for _, r := range fl {
			if !strings.ContainsRune(flags, r) {
				flags += string(r)
			}
		}
		p = p[end+1:]
	}
	for _, bad := range []string{`\A`, `\z`, `\Q`, `\C`, `[[:`} {
		if strings.Contains(p, bad) {
			return "", fmt.Errorf("pattern %q: %s нь JS RegExp-д дэмжигдэхгүй", p, bad)
		}
	}
	p = strings.ReplaceAll(p, "(?P<", "(?<")
	if strings.Contains(p, `\p{`) || strings.Contains(p, `\P{`) {
		flags += "u"
	}
	if flags == "" {
		return "new RegExp(" + jsStr(p) + ")", nil
	}
	return "new RegExp(" + jsStr(p) + ", " + jsStr(flags) + ")", nil
}

