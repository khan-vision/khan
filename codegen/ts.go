// TSOptions — TS гаралтын тохиргоо. Хоосон талбар = front_end-ийн анхдагч.
type TSOptions struct {
	ZodImport     string // анхдагч "zod" (v4)
	AxiosImport   string // анхдагч "~/plugins/core/axios" (Ref талбарын load)
	KvFieldImport string // анхдагч "~/modules/kvform/types" (KvFieldDef)
	AntRuleImport string // анхдагч "~/modules/kvform/antRules" (AntRule)
	// Names — resource Name → TS identifier (PascalCase) override. Хоёр resource-ийн нэрийн сүүлийн
	// сегмент давхцвал (ж: finance.item, inventory.item) энд ялгана; үгүй бол алдаа.
	Names map[string]string
}

func (o TSOptions) withDefaults() TSOptions {
	def := func(p *string, v string) {
		if *p == "" {
			*p = v
		}
	}
	def(&o.ZodImport, "zod")
	def(&o.AxiosImport, "~/plugins/core/axios")
	def(&o.KvFieldImport, "~/modules/kvform/types")
	def(&o.AntRuleImport, "~/modules/kvform/antRules")
	return o
}

// TS — metas-аас TypeScript файл үүсгэнэ (deterministic). Resource бүрд:
//
//	<Pascal>Payload / <Pascal>UpdatePayload / <Pascal>Row (+ child бүрд <Pascal><Child>Payload|Row),
//	<camel>Schema / <camel>UpdateSchema (zod v4), <camel>Fields: KvFieldDef[],
//	<camel>Endpoint, <camel>Filterable, <camel>Defaults.
//
// Decimal (Money/Number): сервер хариунд яг цифртэй JSON ТОО буцаадаг тул Row-д `number`;
// харин хүсэлтэд JSON тоо эсвэл тоон мөр хүлээн авдаг тул Payload-д `number | string`, zod нь
// хоёуланг зөвшөөрч Money-д бутархай ≤ 2, Number-д ≤ Scale орныг шалгана. АНХААР: JS number нь ~15-16
// мэдэгдэхүйц цифрээс хэтэрвэл нарийвчлал алддаг (numeric(18,2)-ийн дээд 9999999999999999.99) —
// том дүнг ЗААВАЛ тоон мөрөөр илгээ, хариуг уншихдаа нарийвчлал чухал бол raw text-ээр задал.
func TS(metas []crud.Meta, opts TSOptions) ([]byte, error) {
	opts = opts.withDefaults()
	g := &tsGen{opts: opts}
	if err := g.plan(metas); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by khan codegen. DO NOT EDIT.\n\n")
	g.writeImports(&b)
	g.writePrelude(&b)
	for _, r := range g.res {
		if err := g.writeResource(&b, r); err != nil {
			return nil, err
		}
	}
	return []byte(b.String()), nil
}

type tsRes struct {
	meta     crud.Meta
	pascal   string
	camel    string
	children []tsChild
}

type tsChild struct {
	meta   crud.ChildMeta
	pascal string // <Pascal><Child>
	camel  string
}

type tsGen struct {
	opts TSOptions
	res  []tsRes

	usesRef, usesNumeric, usesDecimal bool
}

// plan — нэр, давхцал, ашиглагдах helper-үүдийг урьдчилан тодорхойлно.
func (g *tsGen) plan(metas []crud.Meta) error {
	sorted := append([]crud.Meta(nil), metas...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	used := map[string]string{} // identifier → тайлбар
	claim := func(id, what string) error {
		if prev, ok := used[id]; ok {
			return fmt.Errorf("khan/codegen: identifier %q давхцав (%s ба %s) — TSOptions.Names-ээр ялга", id, prev, what)
		}
		used[id] = what
		return nil
	}
	for _, m := range sorted {
		pascal, err := resourcePascal(m.Name, g.opts.Names)
		if err != nil {
			return err
		}
		r := tsRes{meta: m, pascal: pascal, camel: lowerFirst(pascal)}
		ids := []string{pascal + "Payload", pascal + "UpdatePayload", pascal + "Row",
			r.camel + "Schema", r.camel + "UpdateSchema", r.camel + "Fields", r.camel + "Endpoint",
			r.camel + "Filterable", r.camel + "Defaults", r.camel + "Scope"}
		for _, id := range ids {
			if err := claim(id, m.Name); err != nil {
				return err
			}
		}
		if m.Endpoint == "" {
			return fmt.Errorf("khan/codegen: %s: Endpoint хоосон", m.Name)
		}
		if err := g.scanFields(m.Name, m.Fields); err != nil {
			return err
		}
		seenChild := map[string]bool{}
		for _, c := range m.Children {
			cp, err := pascalOf("x." + c.Name)
			if err != nil {
				return fmt.Errorf("khan/codegen: %s: child %q: %w", m.Name, c.Name, err)
			}
			if seenChild[c.Name] {
				return fmt.Errorf("khan/codegen: %s: child %q давхардсан", m.Name, c.Name)
			}
			seenChild[c.Name] = true
			tc := tsChild{meta: c, pascal: pascal + cp, camel: r.camel + cp}
			for _, id := range []string{tc.pascal + "Payload", tc.pascal + "Row", tc.camel + "Schema", tc.camel + "Fields"} {
				if err := claim(id, m.Name+"."+c.Name); err != nil {
					return err
				}
			}
			if err := g.scanFields(m.Name+"."+c.Name, c.Fields); err != nil {
				return err
			}
			r.children = append(r.children, tc)
		}
		g.res = append(g.res, r)
	}
	return nil
}

func (g *tsGen) scanFields(where string, fields []crud.FieldMeta) error {
	seen := map[string]bool{}
	for _, f := range fields {
		if !f.Kind.Valid() {
			return fmt.Errorf("khan/codegen: %s.%s: үл мэдэгдэх kind %q", where, f.Name, f.Kind)
		}
		if f.Name == "" || seen[f.Name] {
			return fmt.Errorf("khan/codegen: %s: талбарын нэр хоосон эсвэл давхардсан (%q)", where, f.Name)
		}
		seen[f.Name] = true
		if f.Ref != nil {
			g.usesRef = true
		}
		switch f.Kind {
		case validate.Int:
			g.usesNumeric = true
		case validate.Money, validate.Number:
			g.usesNumeric, g.usesDecimal = true, true
		}
	}
	return nil
}

func (g *tsGen) writeImports(b *strings.Builder) {
	fmt.Fprintf(b, "import { z } from %s\n", jsStr(g.opts.ZodImport))
	if g.usesRef {
		fmt.Fprintf(b, "import axios from %s\n", jsStr(g.opts.AxiosImport))
	}
	fmt.Fprintf(b, "import type { KvFieldDef } from %s\n", jsStr(g.opts.KvFieldImport))
	if g.usesNumeric {
		fmt.Fprintf(b, "import type { AntRule } from %s\n", jsStr(g.opts.AntRuleImport))
	}
	b.WriteString("\n")
}

func (g *tsGen) writePrelude(b *strings.Builder) {
	if g.usesRef {
		b.WriteString(`type KhanOption = { value: string | number; label: string; parent_value?: string | number | null }

/** Ref талбарын сонголт: GET <endpoint>/options/<field>?search= → {data:[{value,label,parent_value}]}. org-ийг сервер JWT-ээр хязгаарлана. */
async function khanOptions(url: string, search: string): Promise<KhanOption[]> {
  const res = await axios.get(url, { params: { search } })
  return (res.data?.data ?? []) as KhanOption[]
}

`)
	}
	if g.usesNumeric {
		b.WriteString(`/**
 * Тоон утга (Int/Number/Money): JSON тоо эсвэл тоон мөр. Алдааны мессеж эсвэл null.
 * Мөрийг float болгохгүй (бутархайн оронг мөрөөр тоолно); Number() зөвхөн min/max харьцуулахад.
 */
function khanCheckNumber(label: string, value: unknown, scale: number, min?: number, max?: number): string | null {
  if (value === null || value === undefined || value === '') return null
  const s = typeof value === 'number' ? (Number.isFinite(value) ? String(value) : '') : String(value).trim()
  if (!/^-?\d+(\.\d+)?$/.test(s)) return label + ': тоо оруулна уу'
  const frac = s.includes('.') ? s.length - s.indexOf('.') - 1 : 0
  if (frac > scale) return scale === 0 ? label + ': бүхэл тоо оруулна уу' : label + ': бутархай хамгийн ихдээ ' + scale + ' орон'
  const n = Number(s)
  if (min !== undefined && n < min) return label + ': ' + min + '-аас багагүй байна'
  if (max !== undefined && n > max) return label + ': ' + max + '-аас ихгүй байна'
  return null
}

/** KvForm/ant дүрэм: тоон талбарын орон ба хязгаар (мөр загварт min/max нь урт гэж тооцогддог тул validator). */
function khanRange(label: string, scale: number, min?: number, max?: number): AntRule {
  return {
    validator: (_rule, value) => {
      const msg = khanCheckNumber(label, value, scale, min, max)
      return msg ? Promise.reject(new Error(msg)) : Promise.resolve()
    },
  }
}

`)
	}
	if g.usesDecimal {
		b.WriteString(`/** Money/Number хүсэлт: JSON тоо эсвэл тоон мөр (сервер хоёуланг хүлээн авна; хариу нь JSON тоо). */
function khanDecimal(label: string, scale: number, min?: number, max?: number) {
  return z.union([z.number(), z.string()]).superRefine((v, ctx) => {
    const msg = khanCheckNumber(label, v, scale, min, max)
    if (msg) ctx.addIssue({ code: 'custom', message: msg })
  })
}

`)
	}
}

