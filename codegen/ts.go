// kvType — Kind → KvField registry төрөл.
func kvType(f crud.FieldMeta) string {
	if f.Input != "" {
		return f.Input
	}
	if f.Ref != nil {
		return "select"
	}
	switch f.Kind {
	case validate.Text, validate.JSON:
		return "textarea"
	case validate.Int, validate.Number:
		return "number"
	case validate.Money:
		return "amount"
	case validate.Bool:
		return "switch"
	case validate.Date:
		return "date"
	case validate.DateTime:
		return "datetime"
	case validate.Time:
		return "time"
	case validate.Enum:
		return "select"
	case validate.Phone:
		return "phone"
	case validate.Password:
		return "password"
	}
	return "text" // String UUID Email
}

// loadable — Ref талбарт /options load тавих эсэх: Input override нь select-төрлийн биш бол
// (ж: "employee") тухайн domain editor өөрийн эх сурвалжтай тул load тавихгүй.
func loadable(f crud.FieldMeta) bool {
	if f.Ref == nil {
		return false
	}
	switch f.Input {
	case "", "select", "multiselect", "autocomplete":
		return true
	}
	return false
}

func writeFields(b *strings.Builder, name string, fields []crud.FieldMeta) error {
	fmt.Fprintf(b, "/** KvForm талбарууд (KvFieldDef[]). */\nexport const %s: KvFieldDef[] = [\n", name)
	for _, f := range fields {
		lbl := label(f)
		b.WriteString("  {\n")
		fmt.Fprintf(b, "    name: %s,\n    label: %s,\n    type: %s,\n", jsStr(f.Name), jsStr(lbl), jsStr(kvType(f)))
		if f.Required && f.Default == nil {
			b.WriteString("    required: true,\n")
		}
		rules, err := fieldRules(f)
		if err != nil {
			return fmt.Errorf("%s: %w", f.Name, err)
		}
		if len(rules) > 0 {
			b.WriteString("    rules: [\n")
			for _, r := range rules {
				fmt.Fprintf(b, "      %s,\n", r)
			}
			b.WriteString("    ],\n")
		}
		if f.Kind == validate.Enum && len(f.Enum) > 0 && f.Ref == nil {
			b.WriteString("    options: [\n")
			for _, v := range f.Enum {
				fmt.Fprintf(b, "      { label: %s, value: %s },\n", jsStr(v), jsStr(v))
			}
			b.WriteString("    ],\n")
		}
		if loadable(f) {
			fmt.Fprintf(b, "    load: (query: string) => khanOptions(%s, query),\n", jsStr(f.Ref.Options))
		}
		b.WriteString("  },\n")
	}
	b.WriteString("]\n\n")
	return nil
}

func fieldRules(f crud.FieldMeta) ([]string, error) {
	lbl := label(f)
	var rules []string
	switch f.Kind {
	case validate.String, validate.Text, validate.Phone, validate.Password, validate.Email:
		if f.MinLen > 0 {
			rules = append(rules, fmt.Sprintf("{ min: %d, message: %s }", f.MinLen, jsStr(lbl+": хамгийн багадаа "+fmt.Sprint(f.MinLen)+" тэмдэгт")))
		}
		if f.MaxLen > 0 {
			rules = append(rules, fmt.Sprintf("{ max: %d, message: %s }", f.MaxLen, jsStr(lbl+": хамгийн ихдээ "+fmt.Sprint(f.MaxLen)+" тэмдэгт")))
		}
		if f.Kind == validate.Email {
			rules = append(rules, "{ type: \"email\", message: "+jsStr(lbl+": имэйл хаяг буруу")+" }")
		}
		if f.Pattern != "" {
			re, err := jsRegExp(f.Pattern)
			if err != nil {
				return nil, err
			}
			msg := f.PatternMsg
			if msg == "" {
				msg = lbl + ": формат буруу"
			}
			rules = append(rules, "{ pattern: "+re+", message: "+jsStr(msg)+" }")
		}
	case validate.Int, validate.Number, validate.Money:
		scale := 0
		if f.Kind != validate.Int {
			scale = decimalScale(f)
		}
		rules = append(rules, "khanRange("+jsStr(lbl)+", "+fmt.Sprint(scale)+minMaxArgs(f)+")")
	}
	return rules, nil
}

// childIDZod — child id-ийн zod илэрхийлэл: IDInt бол эерэг бүхэл тоо, үгүй бол UUID.
func childIDZod(c crud.ChildMeta, idKey string) string {
	if c.ID.Kind == crud.IDInt {
		return "z.number().int().positive(" + jsStr(idKey+" буруу") + ")"
	}
	return "z.string().regex(" + uuidRe + ", " + jsStr(idKey+" буруу") + ")"
}

// childIDColumn — child мөрийн id-ийн түлхүүр (crud.ChildMeta.ID.Column; хоосон бол "id").
func childIDColumn(c crud.ChildMeta) string {
	if c.ID.Column != "" {
		return c.ID.Column
	}
	return "id"
}

// scopeNote — tenant биш resource-ийн scope тайлбар (TS comment, OpenAPI description). tenant → "".
func scopeNote(m crud.Meta) string {
	switch m.Scope {
	case "shared":
		n := "Scope=shared: org_id NULL мөр = бүх байгууллагад харагдах СИСТЕМИЙН мөр (унших-л; `org_id` null). Create үргэлж өөрийн org."
		if m.SystemWrites {
			n += " Системийн мөрийг зөвхөн SystemCan эрхтэй `POST " + m.Endpoint + "/system`, PUT, DELETE-ээр удирдана."
		} else {
			n += " Системийн мөр засах/устгах боломжгүй (403)."
		}
		return docText(n)
	case "global":
		n := "Scope=global: org_id-гүй платформын хүснэгт, бүх байгууллагад ижил өгөгдөл."
		if m.GlobalWrites {
			n += " Бичилт бүх байгууллагад нөлөөлнө (sysadmin эрх)."
		} else {
			n += " Унших-л."
		}
		return docText(n)
	}
	return ""
}
