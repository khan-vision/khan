func enumUnion(vals []string) string {
	parts := make([]string, len(vals))
	for i, v := range vals {
		parts[i] = jsStr(v)
	}
	return strings.Join(parts, " | ")
}

// tsType — талбарын TS төрөл. row=true: хариу (Money/Number → number), false: хүсэлт (number | string).
func tsType(f crud.FieldMeta, row bool) string {
	switch f.Kind {
	case validate.Int:
		return "number"
	case validate.Money, validate.Number:
		if row {
			return "number"
		}
		return "number | string"
	case validate.Bool:
		return "boolean"
	case validate.Enum:
		if len(f.Enum) > 0 {
			return enumUnion(f.Enum)
		}
		return "string"
	case validate.JSON:
		return "unknown"
	}
	return "string" // String Text Date DateTime Time UUID Password Phone Email
}

// optionalOnCreate — create payload-д талбар заавал биш эсэх (Default байвал сервер нөхнө).
func optionalOnCreate(f crud.FieldMeta) bool { return !f.Required || f.Default != nil }

func idTSType(k crud.IDKind) string {
	if k == crud.IDInt {
		return "number"
	}
	return "string"
}

func (g *tsGen) writeResource(b *strings.Builder, r tsRes) error {
	m := r.meta
	fmt.Fprintf(b, "// ---- %s (%s) ----\n\n", docText(m.Name), docText(m.Label))
	fmt.Fprintf(b, "/** %s: REST суурь. */\nexport const %sEndpoint = %s\n\n", docText(m.Label), r.camel, jsStr(m.Endpoint))
	if note := scopeNote(m); note != "" {
		fmt.Fprintf(b, "/** %s */\n", note)
		fmt.Fprintf(b, "export const %sScope = %s as const\n\n", r.camel, jsStr(m.Scope))
	}

	// Payload / Row interface-ууд (child эхэлж)
	for _, c := range r.children {
		idKey := childIDColumn(c.meta)
		writeInterface(b, c.pascal+"Payload", c.meta.Label+" — мөр (хүсэлт). `"+idKey+"` байвал засна, байхгүй бол шинээр нэмнэ.",
			append([]ifaceMember{{name: idKey, typ: idTSType(c.meta.ID.Kind), opt: true, doc: "Байгаа мөрийн id"}}, payloadMembers(c.meta.Fields)...))
		rowMembers := []ifaceMember{{name: idKey, typ: idTSType(c.meta.ID.Kind)}}
		rowMembers = append(rowMembers, rowFieldMembers(c.meta.Fields)...)
		writeInterface(b, c.pascal+"Row", c.meta.Label+" — мөр (хариу).", rowMembers)
	}
	pm := payloadMembers(m.Fields)
	for _, c := range r.children {
		pm = append(pm, ifaceMember{name: c.meta.Name, typ: c.pascal + "Payload[]", opt: true,
			doc: c.meta.Label + ": бүрэн жагсаалт (түлхүүр алга бол өөрчлөгдөхгүй)"})
	}
	writeInterface(b, r.pascal+"Payload", m.Label+" — үүсгэх хүсэлт.", pm)

	var createOnly []string
	for _, f := range m.Fields {
		if f.CreateOnly {
			createOnly = append(createOnly, f.Name)
		}
	}
	updType := r.pascal + "Payload"
	if len(createOnly) > 0 {
		keys := make([]string, len(createOnly))
		for i, k := range createOnly {
			keys[i] = jsStr(k)
		}
		updType = "Omit<" + updType + ", " + strings.Join(keys, " | ") + ">"
	}
	updType = "Partial<" + updType + ">"
	if m.Version != "" {
		updType += " & { " + propKey(m.Version) + ": number }"
	}
	fmt.Fprintf(b, "/** %s — засах хүсэлт (хэсэгчилсэн%s). */\nexport type %sUpdatePayload = %s\n\n", docText(m.Label),
		map[bool]string{true: "; version заавал"}[m.Version != ""], r.pascal, updType)

	rm := []ifaceMember{{name: m.ID.Column, typ: idTSType(m.ID.Kind)}, {name: "org_id", typ: "string", opt: true}}
	if m.Version != "" {
		rm = append(rm, ifaceMember{name: m.Version, typ: "number"})
	}
	rm = append(rm, rowFieldMembers(m.Fields)...)
	for _, c := range r.children {
		rm = append(rm, ifaceMember{name: c.meta.Name, typ: c.pascal + "Row[]"})
	}
	for _, s := range []string{"created_at", "updated_at", "deleted_at"} {
		rm = append(rm, ifaceMember{name: s, typ: "string | null", opt: true})
	}
	for _, s := range []string{"created_by", "updated_by"} {
		rm = append(rm, ifaceMember{name: s, typ: "string | null", opt: true})
	}
	writeInterface(b, r.pascal+"Row", m.Label+" — дэлгэрэнгүй мөр (хариу). Money/Number нь JSON тоо; Password хариунд байхгүй.", rm)

	// zod
	for _, c := range r.children {
		idKey := childIDColumn(c.meta)
		members := []string{propKey(idKey) + ": " + childIDZod(c.meta, idKey) + ".optional()"}
		if err := appendZodFields(&members, c.meta.Fields); err != nil {
			return fmt.Errorf("khan/codegen: %s.%s: %w", m.Name, c.meta.Name, err)
		}
		fmt.Fprintf(b, "export const %sSchema = z.object({\n%s\n})\n\n", c.camel, indentLines(members))
	}
	var members []string
	if err := appendZodFields(&members, m.Fields); err != nil {
		return fmt.Errorf("khan/codegen: %s: %w", m.Name, err)
	}
	for _, c := range r.children {
		expr := "z.array(" + c.camel + "Schema)"
		if c.meta.MaxRows > 0 {
			expr += fmt.Sprintf(".max(%d, %s)", c.meta.MaxRows, jsStr(fmt.Sprintf("%s: хамгийн ихдээ %d мөр", c.meta.Label, c.meta.MaxRows)))
		}
		members = append(members, propKey(c.meta.Name)+": "+expr+".optional()")
	}
	ctor := "z.object"
	if m.StrictUnknown {
		ctor = "z.strictObject"
	}
	fmt.Fprintf(b, "export const %sSchema = %s({\n%s\n})\n\n", r.camel, ctor, indentLines(members))

	upd := r.camel + "Schema.partial()"
	if len(createOnly) > 0 {
		omit := make([]string, len(createOnly))
		for i, k := range createOnly {
			omit[i] = propKey(k) + ": true"
		}
		upd += ".omit({ " + strings.Join(omit, ", ") + " })"
	}
	if m.Version != "" {
		upd += ".extend({ " + propKey(m.Version) + ": z.number().int().min(0) })"
	}
	fmt.Fprintf(b, "export const %sUpdateSchema = %s\n\n", r.camel, upd)

	// KvFieldDef[]
	for _, c := range r.children {
		if err := writeFields(b, c.camel+"Fields", c.meta.Fields); err != nil {
			return fmt.Errorf("khan/codegen: %s.%s: %w", m.Name, c.meta.Name, err)
		}
	}
	if err := writeFields(b, r.camel+"Fields", m.Fields); err != nil {
		return fmt.Errorf("khan/codegen: %s: %w", m.Name, err)
	}

	// Filterable
	keys := make([]string, 0, len(m.Filterable))
	for k := range m.Filterable {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("/** Жагсаалтын шүүлтийн түлхүүр → төрөл (listquery). */\n")
	if len(keys) == 0 {
		fmt.Fprintf(b, "export const %sFilterable = {} as const\n\n", r.camel)
	} else {
		fmt.Fprintf(b, "export const %sFilterable = {\n", r.camel)
		for _, k := range keys {
			fmt.Fprintf(b, "  %s: %s,\n", propKey(k), jsStr(string(m.Filterable[k])))
		}
		b.WriteString("} as const\n\n")
	}

	// Defaults
	var defs []string
	for _, f := range m.Fields {
		if f.Default == nil {
			continue
		}
		lit, err := jsonLit(f.Default)
		if err != nil {
			return fmt.Errorf("khan/codegen: %s.%s: default кодлох боломжгүй: %w", m.Name, f.Name, err)
		}
		defs = append(defs, propKey(f.Name)+": "+lit)
	}
	fmt.Fprintf(b, "/** Шинэ бичлэгийн анхны утга (Field.Default). */\nexport const %sDefaults: Partial<%sPayload> = {", r.camel, r.pascal)
	if len(defs) == 0 {
		b.WriteString("}\n\n")
	} else {
		b.WriteString("\n" + indentLines(defs) + "\n}\n\n")
	}
	return nil
}

type ifaceMember struct {
	name, typ, doc string
	opt            bool
}

func payloadMembers(fields []crud.FieldMeta) []ifaceMember {
	out := make([]ifaceMember, 0, len(fields))
	for _, f := range fields {
		t := tsType(f, false)
		if f.Nullable && f.Kind != validate.JSON {
			t += " | null"
		}
		opt := optionalOnCreate(f)
		out = append(out, ifaceMember{name: f.Name, typ: t, opt: opt, doc: f.Label})
	}
	return out
}

func rowFieldMembers(fields []crud.FieldMeta) []ifaceMember {
	out := make([]ifaceMember, 0, len(fields))
	for _, f := range fields {
		if f.Kind == validate.Password {
			continue // hash хариунд хэзээ ч гарахгүй
		}
		t := tsType(f, true)
		if (f.Nullable || !f.Required) && f.Kind != validate.JSON {
			t += " | null"
		}
		out = append(out, ifaceMember{name: f.Name, typ: t, doc: f.Label})
	}
	return out
}

func writeInterface(b *strings.Builder, name, doc string, members []ifaceMember) {
	fmt.Fprintf(b, "/** %s */\nexport interface %s {\n", docText(doc), name)
	for _, m := range members {
		if m.doc != "" {
			fmt.Fprintf(b, "  /** %s */\n", docText(m.doc))
		}
		q := ""
		if m.opt {
			q = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s\n", propKey(m.name), q, m.typ)
	}
	b.WriteString("}\n\n")
}

func indentLines(lines []string) string {
	out := make([]string, len(lines))
	for i, l := range lines {
		out[i] = "  " + l + ","
	}
	return strings.Join(out, "\n")
}

